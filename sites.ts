export type Suitability = 'excellent' | 'very-good' | 'good' | 'fair'

export function suitability(site: Site): Suitability {
  if (site.bortle <= 2) return 'excellent'
  if (site.bortle === 3) return 'very-good'
  if (site.bortle === 4) return 'good'
  return 'fair'
}

